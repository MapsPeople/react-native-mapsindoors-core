/**
 * The built-in arrow shape drawn when the stamp type is {@link MPRouteStampType.arrow}.
 *
 * @export
 * @enum {string}
 */
export enum MPRouteArrowStyle {
    /**
     * A single chevron pointing along the route.
     */
    chevron = "chevron",
    /**
     * Two stacked chevrons pointing along the route.
     */
    chevronDouble = "chevronDouble",
    /**
     * A solid triangle pointing along the route.
     */
    triangle = "triangle",
    /**
     * A shaft with an arrowhead, pointing along the route.
     */
    arrow = "arrow",
    /**
     * A solid navigation dart pointing along the route.
     */
    dart = "dart",
}
